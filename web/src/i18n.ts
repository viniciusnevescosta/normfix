const intentionallyIdentical = new Set<MessageKey>([
  "diff",
  "emailPlaceholder",
  "github",
  "norminette",
]);

function placeholders(message: string): string[] {
  return [...message.matchAll(/\{([a-z][a-zA-Z0-9]*)\}/g)].map((match) => match[1] ?? "").sort();
}

export function translationCatalogueProblems(): string[] {
  const problems: string[] = [];
  for (const locale of SUPPORTED_LOCALES.filter((candidate) => candidate !== "en")) {
    for (const key of Object.keys(english) as MessageKey[]) {
      const localized = messages[locale][key];
      if (localized === english[key] && !intentionallyIdentical.has(key)) {
        problems.push(`${locale}.${key} still equals English`);
      }
      if (placeholders(localized).join("\0") !== placeholders(english[key]).join("\0")) {
        problems.push(`${locale}.${key} does not preserve its placeholders`);
      }
    }
  }
  return problems;
}

export function detectLocale(): Locale {
  for (const language of navigator.languages) {
    const candidate = language.toLowerCase().split("-")[0];
    if (SUPPORTED_LOCALES.includes(candidate as Locale)) return candidate as Locale;
  }
  return "en";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

/**
 * Translates a message whose wording depends on a count.
 *
 * The catalogue holds one entry per CLDR plural category, named after it —
 * `importedOne`, `importedOther`. English, Portuguese, Spanish, and French use
 * only `one` and `other`, but a locale with more categories can add its own
 * entries without changing any call site, and anything unpublished falls back
 * to `other`.
 *
 * Every pluralized message must depend on exactly one count. A sentence with
 * two of them cannot agree in every language, so write two sentences.
 */
export function translatePlural(
  locale: Locale,
  base: string,
  count: number,
  values: Readonly<Record<string, string | number>> = {},
): string {
  const category = new Intl.PluralRules(locale).select(count);
  const specific = `${base}${category[0]?.toUpperCase() ?? ""}${category.slice(1)}`;
  const key = (specific in english ? specific : `${base}Other`) as MessageKey;
  return translate(locale, key, { ...values, count });
}
